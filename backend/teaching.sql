CREATE TABLE IF NOT EXISTS ci_teachers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 first_name VARCHAR(100) NOT NULL,
 last_name VARCHAR(100) NOT NULL,
 phone VARCHAR(50) NOT NULL DEFAULT '',
 email VARCHAR(190) NOT NULL DEFAULT '',
 deleted_at DATETIME NULL,
 INDEX(owner_id),
 FOREIGN KEY(user_id) REFERENCES api_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ci_groups (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 plan_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(190) NOT NULL,
 student_count INT UNSIGNED NOT NULL,
 UNIQUE KEY uq_ci_group_owner(owner_id,name),
 FOREIGN KEY(plan_id) REFERENCES ci_plans(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ci_rooms (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(190) NOT NULL,
 building VARCHAR(190) NOT NULL DEFAULT '',
 capacity INT UNSIGNED NOT NULL,
 room_type VARCHAR(100) NOT NULL,
 UNIQUE KEY uq_ci_room_owner(owner_id,building,name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ci_assignments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 group_id BIGINT UNSIGNED NOT NULL,
 module_id BIGINT UNSIGNED NOT NULL,
 teacher_id BIGINT UNSIGNED NOT NULL,
 UNIQUE KEY uq_ci_assignment(owner_id,group_id,module_id,teacher_id),
 FOREIGN KEY(group_id) REFERENCES ci_groups(id),
 FOREIGN KEY(module_id) REFERENCES ci_modules(id),
 FOREIGN KEY(teacher_id) REFERENCES ci_teachers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ci_lessons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 assignment_id BIGINT UNSIGNED NOT NULL,
 room_id BIGINT UNSIGNED NOT NULL,
 starts_at DATETIME NOT NULL,
 ends_at DATETIME NOT NULL,
 INDEX ix_ci_lesson_times(owner_id,starts_at,ends_at),
 FOREIGN KEY(assignment_id) REFERENCES ci_assignments(id),
 FOREIGN KEY(room_id) REFERENCES ci_rooms(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
